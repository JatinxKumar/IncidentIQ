/**
 * types/index.ts — Shared domain types for IncidentIQ
 *
 * This is the single source of truth for all frontend TypeScript types.
 * These mirror the backend domain entities defined in the SRS.
 *
 * Rules:
 * - Every domain entity has an interface here
 * - Never duplicate these types in feature files — always import from here
 * - API response shapes should match these interfaces exactly
 * - Nullable fields use `T | null`, not `T | undefined`
 */

// ─── Enumerations ─────────────────────────────────────────────────────────────

/** Anomaly and incident severity levels — maps to visual color coding */
export type SeverityLevel = 'INFO' | 'WARNING' | 'CRITICAL';

/** Incident lifecycle states */
export type IncidentStatus = 'OPEN' | 'INVESTIGATING' | 'RESOLVED' | 'CLOSED';

/** User access roles — controls which UI sections and actions are visible */
export type UserRole = 'admin' | 'sre' | 'manager' | 'ml_engineer';

/** ML algorithm identifiers — one per trained model */
export type AlgorithmType =
  | 'decision_tree'
  | 'random_forest'
  | 'knn'
  | 'svm'
  | 'linear_regression'
  | 'kmeans';

/** Model lifecycle states */
export type ModelStatus = 'training' | 'completed' | 'failed' | 'active';

/** Training job queue states */
export type JobStatus = 'queued' | 'running' | 'completed' | 'failed';

/** Log severity levels */
export type LogLevel = 'DEBUG' | 'INFO' | 'WARN' | 'ERROR' | 'FATAL';

// ─── Auth ─────────────────────────────────────────────────────────────────────

export interface User {
  id: string;
  email: string;
  role: UserRole;
  createdAt: string;
}

export interface AuthTokens {
  accessToken: string;
  expiresIn: number; // seconds
}

// ─── Telemetry ────────────────────────────────────────────────────────────────

export interface MetricPoint {
  id: string;
  sourceId: string;
  serviceName: string;
  metricName: string;
  value: number;
  unit: string;
  timestamp: string;
  labels: Record<string, string>;
  ingestedAt: string;
}

export interface LogEntry {
  id: string;
  sourceId: string;
  serviceName: string;
  level: LogLevel;
  message: string;
  parsedFields: Record<string, unknown>;
  timestamp: string;
  ingestedAt: string;
}

export interface DataSource {
  id: string;
  name: string;
  type: string;
  createdBy: string;
  createdAt: string;
}

// ─── Anomaly Detection ────────────────────────────────────────────────────────

export interface Anomaly {
  id: string;
  serviceName: string;
  metricName: string;
  /** Confidence score from the ensemble model: 0.0 – 1.0 */
  score: number;
  severity: SeverityLevel;
  modelId: string;
  /** Human-readable explanation generated from the Decision Tree path */
  explanation: string;
  /** Snapshot of the feature vector at time of detection */
  featureSnapshot: Record<string, number>;
  detectedAt: string;
}

export interface AnomalyStreamEvent {
  type: 'anomaly';
  data: Anomaly;
}

// ─── Incidents ────────────────────────────────────────────────────────────────

export interface Incident {
  id: string;
  title: string;
  description: string;
  severity: SeverityLevel;
  status: IncidentStatus;
  /** Mean Time to Detect in seconds */
  mttd: number | null;
  /** Mean Time to Resolve in seconds */
  mttr: number | null;
  createdBy: string;
  createdAt: string;
  resolvedAt: string | null;
  anomalyCount: number;
  tags: string[];
}

export interface IncidentComment {
  id: string;
  incidentId: string;
  userId: string;
  content: string;
  createdAt: string;
}

export interface IncidentTimeline {
  incident: Incident;
  anomalies: Anomaly[];
  comments: IncidentComment[];
  rootCause: RootCauseAnalysis | null;
}

// ─── Root Cause Analysis ──────────────────────────────────────────────────────

export interface ContributingFactor {
  featureName: string;
  /** Importance weight: 0.0 – 1.0 */
  importance: number;
  actualValue: number;
  expectedValue: number;
  /** Human-readable description of why this factor contributed */
  explanation: string;
}

export interface RootCauseAnalysis {
  incidentId: string;
  primaryService: string;
  primaryMetric: string;
  contributingFactors: ContributingFactor[];
  /** Plain-English summary generated by RCA engine */
  summary: string;
  confidence: number;
  generatedAt: string;
}

// ─── ML Models ────────────────────────────────────────────────────────────────

export interface ModelVersion {
  id: string;
  algorithm: AlgorithmType;
  status: ModelStatus;
  hyperparameters: Record<string, unknown>;
  datasetId: string;
  activatedAt: string | null;
  createdAt: string;
}

/** Confusion matrix layout: [[TN, FP], [FN, TP]] */
export type ConfusionMatrix = [[number, number], [number, number]];

export interface ModelEvaluation {
  modelId: string;
  accuracy: number;
  precision: number;
  recall: number;
  f1Score: number;
  rocAuc: number;
  confusionMatrix: ConfusionMatrix;
  evaluatedAt: string;
}

export interface ModelComparison {
  modelA: ModelVersion & { evaluation: ModelEvaluation };
  modelB: ModelVersion & { evaluation: ModelEvaluation };
}

export interface TrainingJob {
  id: string;
  modelId: string;
  status: JobStatus;
  progress: number; // 0–100
  errorMessage: string | null;
  startedAt: string | null;
  completedAt: string | null;
}

export interface FeatureImportance {
  featureName: string;
  importance: number;
}

// ─── Analytics ────────────────────────────────────────────────────────────────

export interface SystemHealthScore {
  /** 0–100, computed from active incident count and anomaly rates */
  score: number;
  activeIncidents: number;
  criticalAnomalies: number;
  warningAnomalies: number;
  infoAnomalies: number;
  updatedAt: string;
}

export interface AnomalyTrendPoint {
  timestamp: string;
  critical: number;
  warning: number;
  info: number;
  total: number;
}

export interface PreprocessingStats {
  totalSamples: number;
  missingValuesFilled: number;
  outliersCapped: number;
  featuresEngineered: number;
  lastRunAt: string;
}

// ─── AI Assistant ─────────────────────────────────────────────────────────────

export interface ChatSession {
  id: string;
  userId: string;
  createdAt: string;
}

export interface ChatMessage {
  id: string;
  sessionId: string;
  role: 'user' | 'assistant';
  content: string;
  /** Context data the assistant used to generate its response */
  contextJson: Record<string, unknown> | null;
  createdAt: string;
}

// ─── Pagination ────────────────────────────────────────────────────────────────

export interface PaginatedResponse<T> {
  data: T[];
  total: number;
  page: number;
  pageSize: number;
  totalPages: number;
}

export interface PaginationParams {
  page?: number;
  pageSize?: number;
}
